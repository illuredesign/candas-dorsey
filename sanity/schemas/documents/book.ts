import {defineType, defineField, defineArrayMember} from 'sanity'
import {BookOpen} from 'lucide-react'

export const bookCategories = [
  {title: 'Novel', value: 'novel'},
  {title: 'Short Fiction Collection', value: 'shortFiction'},
  {title: 'Anthology (edited)', value: 'anthology'},
  {title: 'Poetry', value: 'poetry'},
  {title: 'Other', value: 'other'},
]

export const book = defineType({
  name: 'book',
  title: 'Book',
  type: 'document',
  icon: BookOpen,
  groups: [
    {name: 'details', title: 'Details', default: true},
    {name: 'content', title: 'Content'},
    {name: 'editions', title: 'Editions'},
    {name: 'reviews', title: 'Reviews & Awards'},
    {name: 'purchase', title: 'Where to Buy'},
    {name: 'seo', title: 'SEO'},
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      group: 'details',
      validation: (Rule) => Rule.required().max(200),
    }),
    defineField({
      name: 'subtitle',
      title: 'Subtitle',
      type: 'string',
      description: 'e.g. "and other stories"',
      group: 'details',
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      description: 'URL: /books/<slug>',
      group: 'details',
      options: {source: 'title', maxLength: 96},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'category',
      title: 'Category',
      type: 'string',
      group: 'details',
      options: {list: bookCategories, layout: 'radio'},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'genre',
      title: 'Genre',
      type: 'string',
      description: 'e.g. "Speculative fiction", "Mystery", "Young adult"',
      group: 'details',
    }),
    defineField({
      name: 'year',
      title: 'First publication year',
      type: 'string',
      group: 'details',
    }),
    defineField({
      name: 'publisher',
      title: 'Original publisher',
      type: 'string',
      group: 'details',
    }),
    defineField({
      name: 'coAuthors',
      title: 'Co-authors / co-editors',
      type: 'array',
      of: [defineArrayMember({type: 'string'})],
      description: 'Other people credited on the cover',
      group: 'details',
    }),
    defineField({
      name: 'isUpcoming',
      title: 'Forthcoming',
      type: 'boolean',
      description: 'Not yet published — shown under Upcoming Publications',
      group: 'details',
      initialValue: false,
    }),
    defineField({
      name: 'order',
      title: 'Sort order',
      type: 'number',
      description: 'Within its category; lower numbers appear first',
      group: 'details',
      validation: (Rule) => Rule.integer().min(0),
    }),
    defineField({
      name: 'coverImage',
      title: 'Cover image',
      type: 'creditedImage',
      group: 'details',
    }),
    defineField({
      name: 'description',
      title: 'Write-up',
      type: 'blockContent',
      description: 'Synopsis or notes about the book',
      group: 'content',
    }),
    defineField({
      name: 'excerpt',
      title: 'Excerpt',
      type: 'blockContent',
      description: 'A sample passage (or intro/outro excerpt for anthologies)',
      group: 'content',
    }),
    defineField({
      name: 'relatedBooks',
      title: 'Related books',
      type: 'array',
      group: 'content',
      of: [defineArrayMember({type: 'reference', to: [{type: 'book'}]})],
    }),
    defineField({
      name: 'editions',
      title: 'Editions',
      type: 'array',
      description: 'Each printing, translation, e-book or audiobook',
      group: 'editions',
      of: [defineArrayMember({type: 'edition'})],
    }),
    defineField({
      name: 'reviews',
      title: 'Reviews',
      type: 'array',
      group: 'reviews',
      of: [defineArrayMember({type: 'review'})],
    }),
    defineField({
      name: 'awards',
      title: 'Awards',
      type: 'array',
      group: 'reviews',
      of: [defineArrayMember({type: 'award'})],
    }),
    defineField({
      name: 'purchaseLinks',
      title: 'Where to buy',
      type: 'array',
      group: 'purchase',
      of: [defineArrayMember({type: 'purchaseLink'})],
    }),
    defineField({
      name: 'seo',
      title: 'SEO & Sharing',
      type: 'seo',
      group: 'seo',
    }),
  ],
  orderings: [
    {title: 'Sort order', name: 'orderAsc', by: [{field: 'order', direction: 'asc'}]},
    {title: 'Year (newest)', name: 'yearDesc', by: [{field: 'year', direction: 'desc'}]},
    {title: 'Title A–Z', name: 'titleAsc', by: [{field: 'title', direction: 'asc'}]},
  ],
  preview: {
    select: {title: 'title', category: 'category', year: 'year', media: 'coverImage'},
    prepare({title, category, year, media}) {
      const label = bookCategories.find((c) => c.value === category)?.title ?? category
      return {title, subtitle: [label, year].filter(Boolean).join(' · '), media}
    },
  },
})
